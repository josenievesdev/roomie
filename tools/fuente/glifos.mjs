/** Marcas que se ponen encima de una letra: tilde, virgulilla, diéresis */
const MARCAS = {
  aguda: ["...#.", "..#.."],
  virgulilla: [".##.#", "#.##."],
  dieresis: [".....", ".#.#."],
};

/**
 * Letra con marca encima, con una fila de aire entre las dos: en minúscula
 * la marca ocupa las filas 8 y 7; en mayúscula, la 11 y la 10 (por eso la
 * fuente sube hasta 12 píxeles).
 */
function conMarca(base, marca) {
  const b = BASE[base];
  const ancho = b.r[0].length;
  // La marca se centra sobre la letra (las letras estrechas la recortan)
  const recorta = (fila) => {
    const quita = Math.max(0, fila.length - ancho);
    const izq = Math.floor(quita / 2);
    return fila.slice(izq, izq + ancho).padEnd(ancho, ".");
  };
  const m = MARCAS[marca].map(recorta);
  const cima = b.t + 3;
  return { t: cima, r: [...m, ".".repeat(ancho), ...b.r] };
}


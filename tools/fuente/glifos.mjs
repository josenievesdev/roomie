/** Marcas que se ponen encima de una letra: tilde, virgulilla, diéresis */
const MARCAS = {
  aguda: ["...#.", "..#.."],
  virgulilla: [".##.#", "#.##."],
  dieresis: [".#.#.", "....."],
};

/**
 * Letra con marca encima: en minúscula la marca ocupa las filas 6 y 5; en
 * mayúscula, la 8 y la 7 (por eso la fuente sube hasta 9 píxeles).
 */
function conMarca(base, marca) {
  const b = BASE[base];
  const ancho = b.r[0].length;
  // La marca se centra sobre la letra (las letras estrechas la recortan)
  const recorta = (fila) => {
    const quita = Math.max(0, fila.length - ancho);
    const izq = Math.floor(quita / 2);
    return fila.slice(izq, izq + ancho).padEnd(ancho, ".");
  };
  const m = MARCAS[marca].map(recorta);
  const cima = b.t + 2;
  // Filas entre la marca y la letra, si la letra no llega arriba (la "i")
  const huecos = [];
  for (let y = cima - 2; y > b.t; y--) huecos.push(".".repeat(ancho));
  return { t: cima, r: [...m, ...huecos, ...b.r] };
}

